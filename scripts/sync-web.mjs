// Copies the pure modules the agents run (contract, remediation options, dispatch gate, places)
// into docs/live/lib so the live app in the browser runs exactly the same code. Run after editing them.
//   npm run sync-web
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
mkdirSync(`${root}docs/live/lib`, { recursive: true });
for (const f of ['contract.mjs', 'remediation.mjs', 'dispatch.mjs', 'places.mjs']) {
  const src = readFileSync(`${root}agents/lib/${f}`, 'utf8');
  writeFileSync(`${root}docs/live/lib/${f}`, `// Generated by scripts/sync-web.mjs from agents/lib/${f}. Edit the original, not this copy.\n${src}`);
  console.log(`synced ${f}`);
}
